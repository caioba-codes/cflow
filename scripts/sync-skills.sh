#!/usr/bin/env bash
# sync-skills.sh — install cflow's canonical skills into each harness.
#
# Source of truth: cflow/skills/<name>/. This script NEVER edits those files.
# It generates harness adapters and installs live copies:
#   - Claude Code (native):  ~/.claude/skills/<name>/            (canonical copied unchanged)
#   - Codex (native):        ~/.codex/skills/<name>/             (canonical copied unchanged)
#   - Codex (prompt):        ~/.codex/prompts/<name>.md         (frontmatter stripped)
#   - Repo adapters (committed): harnesses/codex/prompts/<name>.md + harnesses/codex/AGENTS.md
#
# Claude's format == canonical skill directories, so there is no harnesses/claude mirror (it would
# just duplicate skills/). Codex prompt fallback differs, so its adapters are generated + committed.
#
# Usage:  scripts/sync-skills.sh [--dry-run]
set -euo pipefail

DRY=0
[ "${1:-}" = "--dry-run" ] && DRY=1

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CFLOW="$(cd "$SCRIPT_DIR/.." && pwd)"
SKILLS_SRC="$CFLOW/skills"

CLAUDE_SKILLS="$HOME/.claude/skills"
CODEX_SKILLS="$HOME/.codex/skills"
CODEX_PROMPTS="$HOME/.codex/prompts"
REPO_CODEX_PROMPTS="$CFLOW/harnesses/codex/prompts"
AGENTS_OUT="$CFLOW/harnesses/codex/AGENTS.md"

run() { if [ "$DRY" = 1 ]; then printf 'DRY:'; printf ' %q' "$@"; printf '\n'; else "$@"; fi; }
note() { printf '%s\n' "$*"; }

# Read a field from the leading --- ... --- frontmatter block.
fm_field() { # $1=file $2=field
  awk -v f="$2" '
    NR==1 && $0=="---" {infm=1; next}
    infm && $0=="---" { if (capture) print out; exit }
    infm {
      if (capture) {
        if ($0 ~ /^[A-Za-z0-9_-]+:[ \t]*/) {
          print out
          exit
        }
        line=$0
        sub(/^[ \t]+/,"",line)
        out = out (out ? " " : "") line
        next
      }
      if ($0 ~ "^"f":") {
        sub("^"f":[ \t]*","")
        if ($0 == ">" || $0 == "|") {
          capture=1
          out=""
          next
        }
        print
        exit
      }
    }
  ' "$1"
}
# Print the body of a SKILL.md with its frontmatter block removed.
strip_fm() { # $1=file
  awk 'NR==1 && $0=="---"{infm=1;next} infm && $0=="---"{infm=0;next} !infm{print}' "$1"
}

[ -d "$SKILLS_SRC" ] || { echo "no skills dir at $SKILLS_SRC" >&2; exit 1; }

note "cflow skills sync — $([ "$DRY" = 1 ] && echo 'DRY RUN (no changes)' || echo 'APPLY')"
note "source: $SKILLS_SRC"
[ -d "$HOME/.codex" ] || note "note: ~/.codex not found — Codex live install skipped (repo adapters still generated)."
note ""

AGENTS_BEGIN="<!-- cflow:skills:begin -->"
AGENTS_END="<!-- cflow:skills:end -->"
snippet="$AGENTS_BEGIN
## cflow skills — when to use
Generated by scripts/sync-skills.sh. Do not hand-edit; edit the canonical SKILL.md and re-run.
"

shopt -s nullglob
for dir in "$SKILLS_SRC"/*/; do
  dir="${dir%/}"
  sk="$dir/SKILL.md"
  [ -f "$sk" ] || continue
  name="$(basename "$dir")"
  desc="$(fm_field "$sk" description)"
  note "• $name"

  # 1) Claude native (canonical directory, unchanged)
  run mkdir -p "$CLAUDE_SKILLS/$name"
  run cp -R "$dir/." "$CLAUDE_SKILLS/$name/"
  note "    claude  -> $CLAUDE_SKILLS/$name/"

  # 2) Codex prompt adapter, committed in the repo
  run mkdir -p "$REPO_CODEX_PROMPTS"
  if [ "$DRY" = 1 ]; then
    note "    codex   -> (generate) $REPO_CODEX_PROMPTS/$name.md"
  else
    strip_fm "$sk" > "$REPO_CODEX_PROMPTS/$name.md"
    note "    codex   -> $REPO_CODEX_PROMPTS/$name.md"
  fi

  # 3) Codex live install (only if Codex is set up locally)
  if [ -d "$HOME/.codex" ]; then
    run mkdir -p "$CODEX_SKILLS/$name" "$CODEX_PROMPTS"
    run cp -R "$dir/." "$CODEX_SKILLS/$name/"
    if [ "$DRY" = 1 ]; then
      note "    codex   -> (install) $CODEX_SKILLS/$name/ + $CODEX_PROMPTS/$name.md"
    else
      cp "$REPO_CODEX_PROMPTS/$name.md" "$CODEX_PROMPTS/$name.md"
      note "    codex   -> $CODEX_SKILLS/$name/ + $CODEX_PROMPTS/$name.md"
    fi
  fi

  snippet="$snippet
- **$name** — $desc"
done

snippet="$snippet
$AGENTS_END"

# 4) AGENTS.md snippet (committed; init-project splices it into a project's AGENTS.md)
run mkdir -p "$(dirname "$AGENTS_OUT")"
if [ "$DRY" = 1 ]; then
  note ""
  note "DRY: would write AGENTS snippet -> $AGENTS_OUT"
else
  printf '%s\n' "$snippet" > "$AGENTS_OUT"
  note ""
  note "AGENTS snippet -> $AGENTS_OUT"
fi

note ""

# ---------------------------------------------------------------------------
# Orphan check — destinations whose source is gone.
#
# The sync only ever copies forward, so deleting or renaming a skill under
# cflow/skills/ leaves the old copy installed in every harness. Both agents keep
# loading a skill that no longer exists upstream, and until now nothing in this
# script's output said so.
#
# WARN ONLY. Never delete. These directories hold skills cflow does not own, and
# a wrong prune would silently remove a working skill from two live harnesses at
# once — a much worse failure than a stale copy. Symlinked entries are skipped
# outright: the ~14 legacy skills point into ~/.dotfiles/.skills and are not
# orphans, they are simply managed somewhere else.
# ---------------------------------------------------------------------------

orphans=0

is_orphan_name() { # $1=name — true when no canonical skill by that name exists
  [ ! -f "$SKILLS_SRC/$1/SKILL.md" ]
}

check_orphan_dirs() { # $1=label $2=root
  local label="$1" root="$2" entry name
  [ -d "$root" ] || return 0
  for entry in "$root"/*/; do
    entry="${entry%/}"
    # A symlink here is someone else's skill mounted into the same directory.
    [ -L "$entry" ] && continue
    name="$(basename "$entry")"
    is_orphan_name "$name" || continue
    note "  ! $label — $name/ (no $SKILLS_SRC/$name/SKILL.md)"
    orphans=$((orphans + 1))
  done
}

check_orphan_prompts() { # $1=label $2=root
  local label="$1" root="$2" entry name
  [ -d "$root" ] || return 0
  for entry in "$root"/*.md; do
    [ -L "$entry" ] && continue
    name="$(basename "$entry" .md)"
    is_orphan_name "$name" || continue
    # Only flag prompts this script installed. Everything in the repo's adapter
    # directory is generated here, so it is the reliable marker of "ours" — that
    # keeps hand-written Codex prompts out of the warning.
    if [ "$root" != "$REPO_CODEX_PROMPTS" ] && [ ! -f "$REPO_CODEX_PROMPTS/$name.md" ]; then
      continue
    fi
    note "  ! $label — $name.md (no $SKILLS_SRC/$name/SKILL.md)"
    orphans=$((orphans + 1))
  done
}

check_orphan_dirs    "claude skills " "$CLAUDE_SKILLS"
check_orphan_dirs    "codex skills  " "$CODEX_SKILLS"
check_orphan_prompts "codex prompts " "$CODEX_PROMPTS"
check_orphan_prompts "repo adapters " "$REPO_CODEX_PROMPTS"

if [ "$orphans" -gt 0 ]; then
  note ""
  note "$orphans orphaned destination(s): a skill was renamed or removed and its"
  note "installed copy is still there. Nothing was deleted — review and remove by"
  note "hand if the source really is gone."
else
  note "no orphaned destinations."
fi

note ""
note "done."
